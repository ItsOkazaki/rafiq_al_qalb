/**
 * ألفاظ دوائية صريحة فقط. لا يدخلها «علاج»: في هذه المادة «علاج القلب» و«علاج
 * الذنوب» مصطلح شرعي مشروع، وإدخاله يصنع رفضاً خاطئاً لأسئلة بحثية سليمة
 * («كم عدد أحاديث علاج القلب؟»). العبارات التي تجمع «علاج» بطلب شخصي مثبتة
 * في المعجم أعلاه بصيغتها الكاملة.
 */
const MEDICATION_CUES = [
  "دواء", "ادويه", "ادوية", "حبه", "حبوب", "جرعه", "جرعات", "منوم", "منومه",
  "مهدئ", "مهدئات", "دوائي", "ملجم", "عقار", "اقراص", "حبتي",
];

/**
 * فعل تناول + حالة طبية (أو دواء صريح) في نافذة قريبة: «وش آخذ من دواء للقلق».
 * «ما علاج القلق في القرآن؟» لا تمرّ هنا (لا فعل تناول ولا كمية).
 */
function detectIntakeForMedicalCondition(norm: string): boolean {
  const tokens = norm.split(" ").filter(Boolean);
  const strip = (t: string) => {
    for (const p of ["وال", "فال", "بال", "كال", "لل", "ال", "و", "ف", "ب", "ك", "ل"]) {
      if (t.startsWith(p) && t.length - p.length >= 3) return t.slice(p.length);
    }
    return t;
  };
  return tokens.some((token, index) => {
    const core = strip(token);
    // فعل تناول فقط، لا أداة كمية: «كم حديثاً في علاج القلق» سؤال إحصائي عن
    // المادة، و«كم حبة» تُغطّيها قاعدة الكمية × الدواء أعلاه.
    if (!INTAKE_CUES.includes(core)) return false;
    const window = tokens.slice(index + 1, index + 6);
    if (window.some((next) => MEDICATION_CUES.includes(strip(next)) && strip(next) !== "دواء")) {
      return true;
    }
    return window.some((next) => MEDICAL_CONDITION_CUES.includes(strip(next)));
  });
}

function detectMedicationQuantityRequest(norm: string): boolean {
  const tokens = norm.split(" ").filter(Boolean);
  const strip = (t: string) => {
    for (const p of ["وال", "فال", "بال", "كال", "لل", "ال", "و", "ف", "ب", "ك", "ل"]) {
      if (t.startsWith(p) && t.length - p.length >= 3) return t.slice(p.length);
    }
    return t;
  };
  return tokens.some((token, index) => {
    if (!QUANTITY_CUES.includes(strip(token))) return false;
    return tokens
      .slice(index + 1, index + 5)
      .some((next) => MEDICATION_CUES.includes(strip(next)));
  });
}

export function detectPrescriptionRequest(query: string): boolean {
  const norm = normalizeArabic(query);
  if (!norm) return false;
  if (PRESCRIPTION_MARKERS.some((m) => norm.includes(normalizeArabic(m)))) return true;
  if (detectMedicationQuantityRequest(norm)) return true;
  return detectIntakeForMedicalCondition(norm);
}

