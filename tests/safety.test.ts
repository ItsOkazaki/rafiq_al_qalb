describe("معجم السلامة مكتوب بصورته المطبَّعة (حماية من المفردات الميّتة)", () => {
  it("كل مفردة في كل مجموعة تساوي صورتها بعد التطبيع", () => {
    const dead: string[] = [];
    for (const [group, items] of Object.entries(SAFETY_LEXICON)) {
      if (group === "SAFETY_PATTERN_SOURCES") continue;
      for (const item of items) {
        if (normalizeArabic(item) !== item) dead.push(`${group}: ${item}`);
      }
    }
    // مجموعات الطبقة التركيبية تُقارن بوحدات من النص المطبَّع، فأي مفردة غير
    // مطبَّعة لا تطابق شيئاً أبداً وتبقى ميّتة في المعجم.
    expect(dead).toEqual([]);
  });

  it("كل مقطع عربي داخل الأنماط مكتوب مطبَّعاً", () => {
    const dead: string[] = [];
    for (const source of SAFETY_LEXICON.SAFETY_PATTERN_SOURCES) {
      for (const run of source.match(/[\u0600-\u06FF]+/g) ?? []) {
        if (normalizeArabic(run) !== run) dead.push(`${run} في /${source}/`);
      }
    }
    expect(dead).toEqual([]);
  });
});
