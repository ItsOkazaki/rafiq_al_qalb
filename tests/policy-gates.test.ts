// ─────────────────────────────────────────────────────────────────────────────
// البوابات بلغة السائل: الصيغ الدارجة يجب أن تُجاب برسالتها الصحيحة،
// لا أن تسقط إلى «لم نجد مادة كافية».
// ─────────────────────────────────────────────────────────────────────────────

describe("بوابة الفتوى بالصيغ الدارجة (سعودية/خليجية/مصرية/شامية)", () => {
  const CASES = [
    "ما حكم الصلاة", "وش حكم الصلاة", "ايش حكم الصيام", "حكمه ايش",
    "ماهو حكم تارك الصلاة", "يجوز ولا ما يجوز", "حلال ولا حرام",
    "وش رأي الشرع في التأمين", "علي اثم ولا لا", "أبغى فتوى في مسألة",
    "افتوني في موضوعي", "وش الحكم الشرعي", "هل يأثم من ترك",
    "ابغى اعرف الحكم الشرعي للقرض",
    "هل قساوة القلب حرام؟",
    "هل التوبة واجبة؟",
    "هل الصلاة مكروهة؟",
  ];
  it.each(CASES)("يردّ برسالة الفتوى لا بامتناع المادة: %s", (q) => {
    expect(detectFatwaRequest(q).isFatwa).toBe(true);
  });

  it("لا يلتقط أسئلة البحث العادية التي لا تطلب حكماً", () => {
    for (const q of [
      "ما أسباب قسوة القلب", "أثر الذنوب على القلب", "كيف أخشع في صلاتي",
      "فضل الصلاة على النبي", "أبواب التوبة في كلام ابن القيم",
    ]) {
      expect(detectFatwaRequest(q).isFatwa, q).toBe(false);
    }
  });
});

describe("بوابة التشخيص بالصيغ الدارجة", () => {
  const CASES = [
    "وش عندي من مرض", "أنا مريض ولا وش", "شخصني", "أشك إن عندي اكتئاب",
    "هل أنا مصاب بالوسواس", "عندي اكتئاب ولا بس كسلان", "وش مرضي",
    "تشخيص حالتي وش هي", "أنا مجنون ولا وش", "وش فيني",
  ];
  it.each(CASES)("يرفض التشخيص الشخصي: %s", (q) => {
    expect(detectDiagnosisRequest(q)).toBe(true);
  });

  it("لا يلتقط مصطلحات المادة الشرعية («القلب المريض»، «الوسواس في الصلاة»)", () => {
    for (const q of [
      "ما علاج القلب القاسي", "أثر المعاصي", "كيف أرقق قلبي",
      "أمراض القلوب وشفاؤها", "علامات القلب المريض عند ابن القيم",
      "علاج الوساوس في الصلاة",
    ]) {
      expect(detectDiagnosisRequest(q), q).toBe(false);
    }
  });
});

describe("بوابة الوصفة بالصيغ الدارجة", () => {
  const CASES = [
    "وش آخذ من دواء للقلق", "كم حبة أنحف", "أبغى حبوب تنومني",
    "عطني روشتة للاكتئاب", "وصف لي دواء", "أي حبة أستعمل للنوم",
    "ابغى خطة علاجية للأرق", "كم ملغ أحتاج",
  ];
  it.each(CASES)("يرفض تحديد الدواء أو الجرعة: %s", (q) => {
    expect(detectPrescriptionRequest(q)).toBe(true);
  });

  it("«العلاج» و«الدواء» مصطلحان شرعيان في هذه المادة فلا يُرفض السؤال البحثي", () => {
    for (const q of [
      "علاج القلب في القرآن", "ما علاج الغفلة", "دواء القسوة عند ابن القيم",
      "علاج الذنوب", "كم حديثاً في علاج القلق", "دواء القسوة عند ابن القيم",
      // ملاحظة: «ما الدواء الذي أستعمله…» ليست هنا عمداً — السياسة المعتمدة
      // (الحالة F06 في المجموعة) تعدّ صيغة المتكلم «دواء + أستعمل» طلب علاج شخصي،
      // وهذا قرار موثّق لا سهو، فلا يُختبر عكسه.
    ]) {
      expect(detectPrescriptionRequest(q), q).toBe(false);
    }
  });
});

describe("ثابت الاتساق: عبارات الأداة المعلنة لا تُرفض بأي بوابة", () => {
  it("كل مرادفات الأبواب وكلماتها وأسئلتها ذات الصلة تبقى قابلة للبحث", () => {
    type AnyTopic = {
      id: string; title?: string; synonyms?: string[];
      keywords?: string[]; relatedQuestions?: string[];
    };
    const refused: string[] = [];
    for (const raw of TOPICS) {
      const t = raw as unknown as AnyTopic;
      const phrases = [
        t.title ?? "",
        ...(t.synonyms ?? []),
        ...(t.keywords ?? []),
        ...(t.relatedQuestions ?? []),
      ];
      for (const q of phrases) {
        if (!q) continue;
        if (
          detectSafetyRisk(q) ||
          detectFatwaRequest(q).isFatwa ||
          detectDiagnosisRequest(q) ||
          detectPrescriptionRequest(q)
        ) {
          refused.push(`${t.id}: ${q}`);
        }
      }
    }
    // هذه العبارات معروضة للمستخدم في الواجهة كأسئلة مقترحة؛ رفض أيٍّ منها
    // بردّ سلامة أو فتوى أو تشخيص يكون خطأً ظاهراً يراه أول مجرِّب.
    expect(refused).toEqual([]);
  });
});

// انحدار على الصيغة الاسمية المجرّدة: «حكم صلاة الحائض» سؤال حكم مباشر، لكنه لا
// يحمل «ما حكم» ولا «هل يجوز» ولا وصفاً حكمياً في آخره، فكان يسقط إلى مسار البحث
// ويُعيد صفحة «عمدة القاري — الرحمة وقساوة القلب» مع سطر «حدود المادة».
describe("بوابة الفتوى — الصيغة الاسمية المجرّدة («حكم …»)", () => {
  const RULING_PHRASES = [
    "حكم صلاة الحائض",
    "حكم صلاة الحائض؟",
    "الحكم في قضاء الصلاة",
    "حكم تكرار الذنب بعد التوبة",
    "أحكام زكاة المال",
    "وحكم الصيام في السفر",
  ];
  it.each(RULING_PHRASES)("يحيل إلى أهل العلم: %s", (q) => {
    expect(detectFatwaRequest(q).isFatwa).toBe(true);
  });

  it("يصنّف مسألة الحيض والصلاة في الإحالة", () => {
    expect(detectFatwaRequest("حكم صلاة الحائض").matter).toBe("مسألة في الحيض");
  });

  it("لا يلتقط أسئلة التعريف ولا الذِكر العارض للكلمة", () => {
    for (const q of [
      "ما معنى حكم الشرع",            // سؤال تعريف لا طلب فتوى
      "تعريف الحكم التكليفي",
      "كيف أحكم على صدق توبتي",        // «أحكم» فعل لا اسم «حكم»
      "لا استطيع التحكم في غضبي",
      "ما أسباب قسوة القلب",
    ]) {
      expect(detectFatwaRequest(q).isFatwa, q).toBe(false);
    }
  });
});
