#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// One-shot corpus repair: cut the commentator's text out of `hadithFullText`.
//
// Why this exists: records ingested from an official sharh page
// (BookToc/ViewServicePage — عمدة القاري، فتح الباري، …) were stored with the
// whole commentary appended to the matn, because `extractMatnFromPage` stopped
// only at page chrome, the next numbered matn, or a `* * *` separator — and a
// sharh page has none of those between the matn and the commentary. The app then
// rendered that contaminated `hadithFullText` under the «الحديث» heading, i.e.
// it labelled official commentary as hadith.
//
// The parser is fixed at the source; this script re-derives the already committed
// corpus with the *same* exported splitter so no hand edit is needed and the run
// is idempotent. The generated files stay generated: they are rewritten by a
// script, atomically, and `npm run alifta:verify` re-checks the result.
//
//   npm run alifta:repair-matn          # apply (rewrites the generated corpus)
//   npm run alifta:repair-matn -- --dry-run   # report only, write nothing
//
// Nothing is invented: the commentary is official text from the same official
// page. It is moved to `explanationText` only when that field is empty, so an
// already verified explanation is never overwritten or concatenated.
// ─────────────────────────────────────────────────────────────────────────────
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { splitMatnAndCommentary, truncateAtBoundary } from './ingest.mjs';

/** Same commentary length convention the ingester applies to a fetched sharh. */
const MAX_EXPLANATION_CHARS = 6000;

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '../..');
const outDir = path.join(root, 'src/lib/corpus/generated');
const jsonPath = path.join(outDir, 'alifta-html-chunks.json');
const tsPath = path.join(outDir, 'alifta-html-chunks.ts');

const dryRun = process.argv.includes('--dry-run');

/** Temp-file + rename so an interrupted write cannot leave a half-written corpus. */
async function writeFileAtomic(target, contents) {
  const tmp = `${target}.tmp`;
  await fs.writeFile(tmp, contents, 'utf8');
  await fs.rename(tmp, target);
}

const rows = JSON.parse(await fs.readFile(jsonPath, 'utf8'));
if (!Array.isArray(rows)) {
  console.error(`FAIL: ${jsonPath} does not hold an array.`);
  process.exit(1);
}

const repaired = [];
for (const row of rows) {
  const full = typeof row.hadithFullText === 'string' ? row.hadithFullText : '';
  if (!full) continue;
  const { matn, commentary, cut } = splitMatnAndCommentary(full);
  if (!cut || !matn || matn === full) continue;

  const had = full.length;
  row.hadithFullText = matn;
  let explanationFilled = false;
  if (!String(row.explanationText ?? '').trim() && commentary.trim().length >= 60) {
    row.explanationText = truncateAtBoundary(commentary, MAX_EXPLANATION_CHARS);
    explanationFilled = true;
  }
  repaired.push({
    id: row.id,
    chapter: row.chapter,
    sourceUrl: row.sourceUrl,
    hadithFullText: { before: had, after: matn.length },
    commentaryMovedToExplanation: explanationFilled,
    explanationAlreadyPresent: Boolean(String(row.explanationText ?? '').trim()) && !explanationFilled,
  });
}

console.log('── Al-Ifta matn/commentary repair ───────────────────────');
console.log(`records scanned            : ${rows.length}`);
console.log(`records with commentary in : ${repaired.length}`);
for (const r of repaired) {
  console.log(
    `  - ${r.id} «${r.chapter}» hadithFullText ${r.hadithFullText.before} → ${r.hadithFullText.after} chars`
    + (r.commentaryMovedToExplanation ? ' (commentary moved to explanationText)' : ' (official explanationText already present, left untouched)'),
  );
  console.log(`      ${r.sourceUrl}`);
}

if (!repaired.length) {
  console.log('Nothing to repair — no record carries commentary inside hadithFullText.');
  process.exit(0);
}

if (dryRun) {
  console.log('DRY RUN: no file was written.');
  process.exit(0);
}

await writeFileAtomic(jsonPath, JSON.stringify(rows, null, 2) + '\n');
await writeFileAtomic(
  tsPath,
  '// AUTO-GENERATED by scripts/alifta-html/ingest.mjs — do not hand-edit.\n'
  + 'import type { CorpusChunk } from "@/lib/types";\n\n'
  + `export const GENERATED_ALIFTA_HTML_CHUNKS: CorpusChunk[] = ${JSON.stringify(rows, null, 2)};\n`,
);

console.log(`PASS: ${repaired.length} record(s) repaired in:`);
console.log(`  ${path.relative(root, jsonPath)}`);
console.log(`  ${path.relative(root, tsPath)}`);
console.log('Re-run `npm run alifta:verify` to confirm the corpus still verifies.');
